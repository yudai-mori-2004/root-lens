#!/usr/bin/env node

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(webRoot, "..");
const definitions = {
  site_agreement: "document/business/documents/current/agreements/site-cooperation-v1.0.md",
  staff_consent: "document/business/documents/current/consents/participant-consent-v1.0.md",
};

function parse(source) {
  const closing = source.startsWith("---\n") ? source.indexOf("\n---\n", 4) : -1;
  const frontMatter = closing === -1 ? "" : source.slice(4, closing);
  const body = closing === -1 ? source : source.slice(closing + 5);
  const title = frontMatter.match(/^title:\s*(.+)$/m)?.[1]?.trim() ?? body.match(/^#\s+(.+)$/m)?.[1]?.trim();
  if (!title) throw new Error("Agreement template has no title");
  const version = frontMatter.match(/^version:\s*(.+)$/m)?.[1]?.trim();
  if (!version) throw new Error("Agreement template has no version");
  return { title, version, body: body.trim() + "\n" };
}

const templates = Object.fromEntries(Object.entries(definitions).map(([kind, relativePath]) => {
  const source = readFileSync(join(repoRoot, relativePath), "utf8");
  const parsed = parse(source);
  return [kind, {
    ...parsed,
    sha256: createHash("sha256").update(parsed.body, "utf8").digest("hex"),
  }];
}));

const output = `// AUTO-GENERATED by scripts/gen-agreement-templates.mjs — DO NOT EDIT.\n` +
  `// Source of truth: document/business/documents/current/{agreements,consents}/*-v1.0.md.\n\n` +
  `export const agreementTemplates = ${JSON.stringify(templates, null, 2)} as const;\n\n` +
  `export type AgreementKind = keyof typeof agreementTemplates;\n`;

writeFileSync(join(webRoot, "content/agreementTemplates.generated.ts"), output, "utf8");
